#pragma once
#include <iostream>
#include <string>
#include <set>
#include <cmath>
#include "../DecisionTree.hh"
#include "../Solutions.hh"
#include "../GsMode.hh"
#include "../common.h"

#include "Generator.hh"

template<N_t N>
class CppGenerator : public Generator<N> {
public:
    std::string mode = "full";
    TreeStats stats;  // Set by caller before generate()

    // Extended stats (set by caller)
    int sortedPathLen = -1;
    int reversePathLen = -1;

    void generate(std::ostream& out, const DTNode<N>& root, const Solutions<N>& solutions) override {
        Context ctx(out, solutions);
        
        emitHeader(ctx);
        emitBody(ctx, root);
        emitFooter(ctx);
    }
    
private:
    struct Context {
        std::ostream& out;
        const Solutions<N>& solutions;
        Context(std::ostream& o, const Solutions<N>& s) : out(o), solutions(s) {}
    };

    void emitHeader(Context& ctx) {
        ctx.out << "#pragma once\n";

        // Emit tree statistics comment block
        if (stats.leaves > 0) {
            double fullness = (double)stats.leaves / std::pow(2.0, stats.maxDepth) * 100.0;
            ctx.out << "// Decision Tree Statistics:\n";
            ctx.out << "//   Leaves: " << stats.leaves << "\n";
            ctx.out << "//   Nodes:  " << stats.nodes << "\n";
            ctx.out << "//   Max depth: " << stats.maxDepth << "\n";
            ctx.out << "//   Min depth: " << stats.minDepth << "\n";
            ctx.out << "//   Average path length: " << stats.avgDepth() << "\n";
            if (sortedPathLen >= 0) {
                ctx.out << "//   Path length (sorted input): " << sortedPathLen << "\n";
            }
            if (reversePathLen >= 0) {
                ctx.out << "//   Path length (reverse input): " << reversePathLen << "\n";
            }
            ctx.out << "//   Tree fullness: " << fullness << "% (" << stats.leaves << " / 2^" << stats.maxDepth << ")\n";
            ctx.out << "\n";
        }

        ctx.out << "#include \"cycle.hh\"\n";

        if (isGsMode(mode)) {
            // Include the kernel headers needed for pre-sorting each group
            auto groups = parseGsGroups(mode);
            std::set<int> kernelSizes;
            for (int g : groups) {
                if (g > 1) kernelSizes.insert(g);
            }
            for (int k : kernelSizes) {
                ctx.out << "#include \"dtsort" << k << "_full.hh\"\n";
            }
        }
        ctx.out << "\n";

        ctx.out << "// Generated by dtsort-codegen\n";
        ctx.out << "#ifndef DT_ADAPTIVE\n#define DT_ADAPTIVE 1\n#endif\n";
        if (isGsMode(mode)) {
            ctx.out << "#ifndef DT_UNLIKELY\n#if defined(__GNUC__) || defined(__clang__)\n#define DT_UNLIKELY(x) __builtin_expect(!!(x), 0)\n#else\n#define DT_UNLIKELY(x) (x)\n#endif\n#endif\n";
        }
        ctx.out << "#define N(label, row, col, labelTrue, labelFalse) label: if (compare(row, col)) goto labelTrue; else goto labelFalse;\n";
        if (mode == "ps") {
            ctx.out << "#define CAS(a, b) if (compare(b, a)) { std::swap(a, b); }\n";
        }
        ctx.out << "#if DT_ADAPTIVE\n";
        ctx.out << "#define R return false;\n";
        ctx.out << "#define R_SORTED return true;\n";
        ctx.out << "#else\n";
        ctx.out << "#define R return;\n";
        ctx.out << "#define R_SORTED return;\n";
        ctx.out << "#endif\n\n";

        // Function name: dtsortN for full, dtsortNps for ps, dtsortNgsXYZ for gs
        std::string suffix;
        if (mode == "ps") suffix = "ps";
        else if (isGsMode(mode)) suffix = mode;  // e.g., "gs53"
        // else suffix stays empty for "full"

        ctx.out << "template<typename RandomAccessIterator, typename Compare>\n";
        ctx.out << "#if defined(__GNUC__) || defined(__clang__)\n";
        ctx.out << "__attribute__((always_inline))\n";
        ctx.out << "#endif\n";
        ctx.out << "#if DT_ADAPTIVE\n";
        ctx.out << "// Returns true if the input was already sorted and no swaps were performed.\n";
        ctx.out << "inline bool dtsort" << (int)N << suffix << "(const RandomAccessIterator& first, const RandomAccessIterator& last, const Compare& compare) {\n";
        ctx.out << "#else\n";
        ctx.out << "inline void dtsort" << (int)N << suffix << "(const RandomAccessIterator& first, const RandomAccessIterator& last, const Compare& compare) {\n";
        ctx.out << "#endif\n";
        ctx.out << "assert(last-first==" << (int)N << ");\n";
        for (int i=0; i<N; ++i) {
            ctx.out << "auto &" << (char)('a'+i) << " = *(first+" << i << ");\n";
        }
        ctx.out << "\n";

        if (isGsMode(mode)) {
            // Emit pre-sort kernel calls for each group
            auto groups = parseGsGroups(mode);
            ctx.out << "#if DT_ADAPTIVE\n";
            int offset = 0;
            for (size_t i = 0; i < groups.size(); ++i) {
                int g = groups[i];
                if (g > 1) {
                    if (offset == 0) {
                        ctx.out << "    bool s" << (i+1) << " = dtsort" << g << "(first, first+" << g << ", compare);\n";
                    } else {
                        ctx.out << "    bool s" << (i+1) << " = dtsort" << g << "(first+" << offset << ", first+" << (offset + g) << ", compare);\n";
                    }
                } else {
                    ctx.out << "    bool s" << (i+1) << " = true;\n";
                }
                offset += g;
            }
            // Build the boundary short-circuit condition for N groups
            ctx.out << "    if (DT_UNLIKELY(";
            for (size_t i = 0; i < groups.size(); ++i) {
                if (i > 0) ctx.out << " && ";
                ctx.out << "s" << (i+1);
            }
            int current_offset = 0;
            for (size_t i = 0; i < groups.size() - 1; ++i) {
                current_offset += groups[i];
                ctx.out << " && !compare(*(first+" << current_offset << "), *(first+" << (current_offset - 1) << "))";
            }
            ctx.out << ")) return true;\n";
            ctx.out << "#else\n";
            
            offset = 0;
            for (int g : groups) {
                if (g > 1) {
                    if (offset == 0) {
                        ctx.out << "dtsort" << g << "(first, first+" << g << ", compare);\n";
                    } else {
                        ctx.out << "dtsort" << g << "(first+" << offset << ", first+" << (offset + g) << ", compare);\n";
                    }
                }
                offset += g;
            }
            ctx.out << "#endif\n\n";
        } else if (mode == "ps") {
            for (int i=0; i+1<N; i+=2) {
                ctx.out << "CAS(" << (char)('a'+i) << ", " << (char)('a'+i+1) << ");\n";
            }
            ctx.out << "\n";
        }
    }
    
    void emitBody(Context& ctx, const DTNode<N>& root) {
        // We use a two-pass approach to generate a flat list of labels.
        // This avoids deep recursion in the generated C++ code (which would use nested ifs)
        // and instead produces a structure similar to assembly (blocks + jumps).
        
        // Pass 1: Emit all decision Nodes (macros N(...))
        // These are the internal nodes of the decision tree.
        PartialMatrix<N> partial; 
        if (mode == "ps") {
            for (int i = 0; i + 1 < N; i += 2) {
                partial.set(i + 1, i, false); // v[i] < v[i+1] is assumed
            }
        } else if (isGsMode(mode)) {
            auto groups = parseGsGroups(mode);
            auto gsIndices = Matrix<N>::getGroupSortedIndices(groups);
            for (size_t idx : gsIndices) {
                partial.set(idx, false);
            }
        }
        emitDecisionNodes(ctx, root, partial);
        
        ctx.out << "\n";
        
        // Pass 2: Emit leaf nodes (labels + actions)
        // These are the solutions (cycle decompositions).

        partial = PartialMatrix<N>(); 
        if (mode == "ps") {
            for (int i = 0; i + 1 < N; i += 2) {
                partial.set(i + 1, i, false);
            }
        } else if (isGsMode(mode)) {
            auto groups = parseGsGroups(mode);
            auto gsIndices = Matrix<N>::getGroupSortedIndices(groups);
            for (size_t idx : gsIndices) {
                partial.set(idx, false);
            }
        }
        emitLeafNodes(ctx, root, partial);
    }
    
    std::string makeLabel(const PartialMatrix<N>& partial, bool isLeaf) {
        // e.g. n10_ or l10_
        std::string s = partial.str_short_lower(); 
        if (N <= 4) {
             return (isLeaf ? "l" : "n") + s;
        } else {
             return (isLeaf ? "l" : "n") + hexify(ternaryToDec(s));
        }
    }
    
    void emitDecisionNodes(Context& ctx, const DTNode<N>& node, PartialMatrix<N>& partial) {
        if (node.isLeaf()) return;
        
        std::string myLabel = makeLabel(partial, false);
        
        std::string trueLabel, falseLabel;
        
        // Peek true child
        partial.set(node.splitIndex(), true);
        trueLabel = makeLabel(partial, node.trueChild->isLeaf());
        partial.unset(node.splitIndex());
        
        // Peek false child
        partial.set(node.splitIndex(), false);
        falseLabel = makeLabel(partial, node.falseChild->isLeaf());
        partial.unset(node.splitIndex());
        
        char r = 'a' + node.row;
        char c = 'a' + node.col;
        
        ctx.out << "N(" << myLabel << ", " << r << ", " << c << ", " << trueLabel << ", " << falseLabel << ")\n";
        
        // Recurse Left
        partial.set(node.splitIndex(), true);
        emitDecisionNodes(ctx, *node.trueChild, partial);
        partial.unset(node.splitIndex());
        
        // Recurse Right
        partial.set(node.splitIndex(), false);
        emitDecisionNodes(ctx, *node.falseChild, partial);
        partial.unset(node.splitIndex());
    }
    
    void emitLeafNodes(Context& ctx, const DTNode<N>& node, PartialMatrix<N>& partial) {
        if (node.isLeaf()) {
            std::string label = makeLabel(partial, true);
            ctx.out << label << ":";
            
            // Generate cycles
            size_t permIdx = node.matchingSolutions[0];
            const auto& mat = ctx.solutions.all[permIdx];
            std::string cycles = mat.perm.decomposedPermutation();
            if (!cycles.empty()) {
                ctx.out << cycles;
                if (cycles.back() != ';') ctx.out << ";";
                ctx.out << "R\n";
            } else {
                ctx.out << "R_SORTED\n";
            }
            return;
        }
        
        // Recurse
        partial.set(node.splitIndex(), true);
        emitLeafNodes(ctx, *node.trueChild, partial);
        partial.unset(node.splitIndex());
        
        partial.set(node.splitIndex(), false);
        emitLeafNodes(ctx, *node.falseChild, partial);
        partial.unset(node.splitIndex());
    }

    void emitFooter(Context& ctx) {
        ctx.out << "}\n";
        ctx.out << "#undef N\n";
        if (mode == "ps") {
            ctx.out << "#undef CAS\n";
        }
        if (isGsMode(mode)) {
            ctx.out << "#undef DT_UNLIKELY\n";
        }
        ctx.out << "#undef R\n";
        ctx.out << "#undef R_SORTED\n";
    }
};
